import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.tasks.await
import java.text.SimpleDateFormat
import java.util.Calendar
import java.util.Date
import java.util.Locale

class DefaultAuditTrailRepository(
    private val firestore: FirebaseFirestore
) : AuditTrailRepository
{

    companion object {
        private const val AUDIT_TRAILS_COLLECTION = "audit_trails"
    }

    override suspend fun createAuditTrail(auditTrail: AuditTrail): Result<AuditTrail, DataError> = runCatching {
        val busRef = firestore.collection(BUSINESS_COLLECTION).document(auditTrail.businessId)
        // correct way to add and get ID
        val docRef = busRef.collection(AUDIT_TRAILS_COLLECTION).add(auditTrail).await()
        // If we want the ID in the returned object, we should copy it.
        // But the stored document will have ID generated by Firestore.
        // To update the document with its own ID:
        // docRef.update("id", docRef.id).await() 
        // But usually not strict requirement if we use @DocumentId
        
        auditTrail.copy(id = docRef.id)
    }.fold(
        onSuccess = {
            Result.Success(it)
                    },
        onFailure = {
            print("eddie" +it.message)
            Result.Error(DataError.Remote.REQUEST_TIMEOUT) }
    )

    override suspend fun getAuditTrails(
        businessId: String,
        paginationRequest: AuditTrailPaginationRequest
    ): Result<AuditTrailDto, DataError.Remote> {
        return try {
            val busRef = firestore.collection(BUSINESS_COLLECTION).document(businessId)
            var query: Query = busRef.collection(AUDIT_TRAILS_COLLECTION)

            // --- Apply Filters ---
            paginationRequest.staff_user_id?.let {
                query = query.whereEqualTo("staffId", it)
            }
            paginationRequest.action_type?.let {
                // Store enums as strings in Firestore
                query = query.whereEqualTo("actionType", it.name)
            }
            paginationRequest.entity_type?.let {
                query = query.whereEqualTo("entityType", it.name)
            }
            paginationRequest.productId?.let {
                query = query.whereEqualTo("productId", it)
            }

            // Date Range Filter
            if (!paginationRequest.start_date.isNullOrBlank()) {
                val sdf = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault())
                paginationRequest.start_date?.let {
                    val start = sdf.parse(it)
                    if (start != null) {
                        query = query.whereGreaterThanOrEqualTo("createdAt", Timestamp(start))
                    }
                }
                paginationRequest.end_date?.let {
                    val end = sdf.parse(it)
                    if (end != null) {
                        val endOfDay = Calendar.getInstance().apply {
                            time = end
                            add(Calendar.DAY_OF_YEAR, 1)
                        }.time
                        query = query.whereLessThan("createdAt", Timestamp(endOfDay))
                    }
                }
            } else {
                // Period Filter (if date range is not set)
                paginationRequest.filter_by?.let {
                    val (start, end) = getStartAndEndTimestamps(it)
                    start?.let { query = query.whereGreaterThanOrEqualTo("createdAt", it) }
                    end?.let { query = query.whereLessThan("createdAt", it) }
                }
            }

            // --- Pagination ---
            // Get total count for pagination
            val countSnapshot = query.count().get(AggregateSource.SERVER).await()
            val total = countSnapshot.count.toInt()
            val limit = paginationRequest.limit
            val totalPages = if (limit == 0) 1 else ((total + limit - 1) / limit)
            val page = paginationRequest.page.toInt()

            // Build paginated query
            var paginatedQuery = query.orderBy("createdAt", Query.Direction.DESCENDING)

            if (page > 1 && total > 0) {
                val offset = (page - 1) * limit
                val prevPageSnapshot = query.orderBy("createdAt", Query.Direction.DESCENDING)
                    .limit(offset.toLong())
                    .get().await()
                if (prevPageSnapshot.documents.isNotEmpty()) {
                    paginatedQuery = paginatedQuery.startAfter(prevPageSnapshot.documents.last())
                }
            }
            paginatedQuery = paginatedQuery.limit(limit.toLong())

            // Execute query and map results
            val snapshot = paginatedQuery.get().await()
            val auditTrails = snapshot.documents.mapNotNull { doc ->
                doc.toObject(AuditTrail::class.java)
            }

            Result.Success(
                AuditTrailDto(
                    auditTrails = auditTrails,
                    totalRecords = total,
                    totalPages = totalPages,
                    limit = limit,
                    page = page
                )
            )
        } catch (e: Exception) {
            e.printStackTrace()
            Result.Error(DataError.Remote.UNKNOWN)
        }
    }

    override suspend fun getAuditTrailsByProduct(productId: String, businessId: String): Flow<List<AuditTrail>> = callbackFlow {
        val busRef = firestore.collection(BUSINESS_COLLECTION).document(businessId)
        val query = busRef.collection(AUDIT_TRAILS_COLLECTION)
            .whereEqualTo("productId", productId)
            .orderBy("createdAt", Query.Direction.DESCENDING)
        val listener = query.addSnapshotListener { snapshot, _ ->
            if (snapshot == null) {
                trySend(emptyList())
                return@addSnapshotListener
            }
            val auditTrails = snapshot.documents.mapNotNull { it.toObject(AuditTrail::class.java) }
            trySend(auditTrails)
        }
        awaitClose { listener.remove() }
    }

    override suspend fun getAuditTrailsByStaff(staffId: String, businessId: String): Flow<List<AuditTrail>> = callbackFlow {
        val busRef = firestore.collection(BUSINESS_COLLECTION).document(businessId)
        val query = busRef.collection(AUDIT_TRAILS_COLLECTION)
            .whereEqualTo("staffId", staffId)
            .orderBy("createdAt", Query.Direction.DESCENDING)
        val listener = query.addSnapshotListener { snapshot, _ ->
            if (snapshot == null) {
                trySend(emptyList())
                return@addSnapshotListener
            }
            val auditTrails = snapshot.documents.mapNotNull { it.toObject(AuditTrail::class.java) }
            trySend(auditTrails)
        }
        awaitClose { listener.remove() }
    }

    override suspend fun getAuditTrailsByTransaction(transactionId: String, businessId: String): Flow<List<AuditTrail>> = callbackFlow {
        val busRef = firestore.collection(BUSINESS_COLLECTION).document(businessId)
        val query = busRef.collection(AUDIT_TRAILS_COLLECTION)
            .whereEqualTo("businessId", businessId)
            .whereEqualTo("transactionId", transactionId)
            .orderBy("createdAt", Query.Direction.DESCENDING)
        val listener = query.addSnapshotListener { snapshot, _ ->
            if (snapshot == null) {
                trySend(emptyList())
                return@addSnapshotListener
            }
            val auditTrails = snapshot.documents.mapNotNull { it.toObject(AuditTrail::class.java) }
            trySend(auditTrails)
        }
        awaitClose { listener.remove() }
    }
    private fun getStartAndEndTimestamps(filter: String?): Pair<Timestamp?, Timestamp?> {
        val cal = Calendar.getInstance().apply {
            set(Calendar.HOUR_OF_DAY, 0); set(Calendar.MINUTE, 0); set(Calendar.SECOND, 0); set(Calendar.MILLISECOND, 0)
        }
        val start: Date; val end: Date
        when (filter) {
            "daily" -> { start = cal.time; cal.add(Calendar.DAY_OF_YEAR, 1); end = cal.time }
            "weekly" -> { cal.set(Calendar.DAY_OF_WEEK, cal.firstDayOfWeek); start = cal.time; cal.add(Calendar.WEEK_OF_YEAR, 1); end = cal.time }
            "monthly" -> { cal.set(Calendar.DAY_OF_MONTH, 1); start = cal.time; cal.add(Calendar.MONTH, 1); end = cal.time }
            else -> return Pair(null, null)
        }
        return Pair(Timestamp(start), Timestamp(end))
    }
}









